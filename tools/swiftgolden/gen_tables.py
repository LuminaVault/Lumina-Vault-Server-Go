#!/usr/bin/env python3
"""Turns probe.swift's output into internal/swiftstr/character_tables.gen.go.

    python3 tools/swiftgolden/gen_tables.py runs.txt backslash.txt > internal/swiftstr/character_tables.gen.go
"""
import sys

NAMES = {
    "control": "charControl", "cr": "charCR", "lf": "charLF", "extend": "charExtend",
    "zwj": "charZWJ", "ri": "charRegional", "prepend": "charPrepend",
    "spacing": "charSpacingMark", "l": "charL", "v": "charV", "t": "charT",
}


def merge(runs):
    out = []
    for lo, hi, v in runs:
        if out and out[-1][1] + 1 == lo and out[-1][2] == v:
            out[-1] = (out[-1][0], hi, v)
        else:
            out.append((lo, hi, v))
    return out


classes, pict, consonant = [], [], []
for line in open(sys.argv[1]):
    lo, hi, cl, p, c, _ws = line.split()
    lo, hi = int(lo, 16), int(hi, 16)
    # Hangul syllables are computed, not listed.
    if cl not in ("any", "lv", "lvt"):
        classes.append((lo, hi, cl))
    if p == "1":
        pict.append((lo, hi, 1))
    if c == "1":
        consonant.append((lo, hi, 1))

print("// Code generated by tools/swiftgolden/gen_tables.py. DO NOT EDIT.")
print("// Source: String.count observed on the Swift 6.3.3 Linux toolchain (tools/swiftgolden/probe.swift).")
print()
print("package swiftstr")
print()
print("var charClasses = []charRange{")
for lo, hi, cl in merge(classes):
    print(f"\t{{0x{lo:X}, 0x{hi:X}, {NAMES[cl]}}},")
print("}")
keep = []
for line in open(sys.argv[2]):
    lo, hi = line.split()
    keep.append((int(lo, 16), int(hi, 16), 1))
for name, runs in (("extendedPictographic", pict), ("incbConsonant", consonant), ("foundationCombining", keep)):
    print()
    print(f"var {name} = []runeRange{{")
    for lo, hi, _ in merge(runs):
        print(f"\t{{0x{lo:X}, 0x{hi:X}}},")
    print("}")
