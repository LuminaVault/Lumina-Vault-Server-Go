// Package migrations embeds the goose migrations. 00001_baseline.sql is the
// schema the Swift server's Fluent migrations produce (Phase 0 Task 0.5); each
// later Swift migration gets a mirrored goose file until Phase 12, when goose
// takes over and `App migrate` runs it in the PreSync job.
package migrations

import (
	"context"
	"database/sql"
	"embed"
	"errors"
	"fmt"
	"io/fs"
	"strings"

	"github.com/jackc/pgx/v5/pgxpool"
	"github.com/jackc/pgx/v5/stdlib"
	"github.com/pressly/goose/v3"
)

//go:embed sql
var embedded embed.FS

// SQL is the embedded migration directory.
func SQL() fs.FS {
	sub, err := fs.Sub(embedded, "sql")
	if err != nil {
		panic(err) // the embed directive guarantees "sql" exists
	}
	return sub
}

// FluentManifest returns the Fluent migration names the baseline covers
// (sql/fluent-manifest.txt, generated with the baseline by Task 0.5).
func FluentManifest() ([]string, error) {
	raw, err := fs.ReadFile(SQL(), "fluent-manifest.txt")
	if err != nil {
		return nil, fmt.Errorf("adopt: %w (generated by Phase 0 Task 0.5)", err)
	}
	var out []string
	for line := range strings.Lines(string(raw)) {
		if line = strings.TrimSpace(line); line != "" && !strings.HasPrefix(line, "#") {
			out = append(out, line)
		}
	}
	return out, nil
}

const (
	gooseTable  = "goose_db_version"
	fluentTable = "_fluent_migrations"
)

// ErrFluentManaged is returned by Up on a database Fluent still owns.
var ErrFluentManaged = errors.New("refusing: database is Fluent-managed; run with --adopt-fluent during decommission")

func provider(pool *pgxpool.Pool, fsys fs.FS) (*goose.Provider, *sql.DB, error) {
	db := stdlib.OpenDBFromPool(pool)
	p, err := goose.NewProvider(goose.DialectPostgres, db, fsys)
	if err != nil {
		_ = db.Close()
		return nil, nil, err
	}
	return p, db, nil
}

// Up applies pending goose migrations from fsys. It refuses a database that
// has Fluent's history table but no goose table: running the baseline there
// would try to recreate every table.
func Up(ctx context.Context, pool *pgxpool.Pool, fsys fs.FS) error {
	fluent, err := tableExists(ctx, pool, fluentTable)
	if err != nil {
		return err
	}
	goosed, err := tableExists(ctx, pool, gooseTable)
	if err != nil {
		return err
	}
	if fluent && !goosed {
		return ErrFluentManaged
	}
	p, db, err := provider(pool, fsys)
	if err != nil {
		return err
	}
	defer func() { _ = db.Close() }()
	_, err = p.Up(ctx)
	return err
}

// AdoptFluent hands a Fluent-managed database to goose without running any
// DDL: it checks that Fluent applied exactly the migrations in manifest, then
// creates goose's table (goose's own Postgres DDL) and marks every embedded
// version applied. Used once, in Phase 12.
func AdoptFluent(ctx context.Context, pool *pgxpool.Pool, fsys fs.FS, manifest []string) error {
	applied, err := fluentNames(ctx, pool)
	if err != nil {
		return err
	}
	if err := sameSet(applied, manifest); err != nil {
		return err
	}
	p, db, err := provider(pool, fsys)
	if err != nil {
		return err
	}
	defer func() { _ = db.Close() }()

	tx, err := pool.Begin(ctx)
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback(ctx) }()
	if _, err := tx.Exec(ctx, `CREATE TABLE `+gooseTable+` (
		id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
		version_id bigint NOT NULL,
		is_applied boolean NOT NULL,
		tstamp timestamp NOT NULL DEFAULT now()
	)`); err != nil {
		return fmt.Errorf("adopt: %w", err)
	}
	versions := []int64{0} // goose records version 0 when it creates its table
	for _, s := range p.ListSources() {
		versions = append(versions, s.Version)
	}
	for _, v := range versions {
		if _, err := tx.Exec(ctx, `INSERT INTO `+gooseTable+` (version_id, is_applied) VALUES ($1, true)`, v); err != nil {
			return fmt.Errorf("adopt: %w", err)
		}
	}
	return tx.Commit(ctx)
}

func tableExists(ctx context.Context, pool *pgxpool.Pool, name string) (bool, error) {
	var ok bool
	err := pool.QueryRow(ctx, `SELECT to_regclass($1) IS NOT NULL`, "public."+name).Scan(&ok)
	return ok, err
}

func fluentNames(ctx context.Context, pool *pgxpool.Pool) ([]string, error) {
	rows, err := pool.Query(ctx, `SELECT name FROM `+fluentTable)
	if err != nil {
		return nil, fmt.Errorf("adopt: reading %s: %w", fluentTable, err)
	}
	defer rows.Close()
	var out []string
	for rows.Next() {
		var n string
		if err := rows.Scan(&n); err != nil {
			return nil, err
		}
		out = append(out, n)
	}
	return out, rows.Err()
}

func sameSet(applied, manifest []string) error {
	want := map[string]bool{}
	for _, m := range manifest {
		want[m] = true
	}
	got := map[string]bool{}
	for _, a := range applied {
		got[a] = true
		if !want[a] {
			return fmt.Errorf("adopt: Fluent applied %q, which fluent-manifest.txt does not list", a)
		}
	}
	for m := range want {
		if !got[m] {
			return fmt.Errorf("adopt: fluent-manifest.txt lists %q, which Fluent never applied", m)
		}
	}
	return nil
}
