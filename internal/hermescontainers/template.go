// GatewayEnvVars is HermesGatewayCatalog.envVars: blank values are left out.
func GatewayEnvVars(id string, config map[string]string) map[string]string {
	out := map[string]string{}
	for _, kv := range gatewayEnvKeys[id] {
		if v := strings.TrimSpace(config[kv[0]]); v != "" {
			out[kv[1]] = v
		}
	}
	return out
}

const baseConfigYAML = `# Auto-generated by HermesContainerManager (HER-254). Do not edit in-place;
# changes are overwritten on container restart unless the SHA-256 matches.

model:
  default: "%s"

platforms:
  api_server:
    enabled: true
    host: 0.0.0.0
    port: 8642

# Messaging gateways (telegram/discord/slack/…) are NOT listed here:
# activation is driven by the presence of each platform's token env-var
# in ` + "`.env`" + ` (see HermesGatewayCatalog.envVars). Listing them with
# ` + "`enabled: false`" + ` is inert for messaging and only risks confusion.

# Access is restricted per-gateway via each platform's *_ALLOWED_USERS
# env-var (seeded from the owner's IDs). NOT open: allow_all_users stays
# false (and is inert anyway — ` + "`gateway run`" + ` reads GATEWAY_ALLOW_ALL_USERS
# from .env, which we deliberately do NOT set).
gateway:
  allow_all_users: false

logging:
  level: INFO`

const audioConfigYAML = `

stt:
  enabled: true
  echo_transcripts: true
  provider: openai
  openai:
    base_url: "%s"
    model: "%s"

tts:
  provider: openai
  openai:
    base_url: "%s"
    model: "%s"
    voice: "%s"`

const mnemosyneConfigYAML = `

# HER-XXX — Mnemosyne is the default memory layer: disable Hermes' native
# curated memory so Mnemosyne (below) is the single source of truth.
memory:
  memory_enabled: false
  user_profile_enabled: false

# HER-XXX — Mnemosyne memory, wired as a Hermes MCP server.
mcp_servers:
  mnemosyne:
    command: mnemosyne
    args: ["mcp"]
    env:
      MNEMOSYNE_DATA_DIR: /opt/data/mnemosyne
      FASTEMBED_CACHE_PATH: /opt/data/mnemosyne/cache`

// ConfigYAML is HermesTenantConfigTemplate.configYAML, byte for byte: the seed is
// SHA-256 drift-compared, so a stray byte would rewrite every tenant's file.
func ConfigYAML(defaultModel string, mnemosyneEnabled bool, audio *AudioProxySeed) string {
	out := fmt.Sprintf(baseConfigYAML, defaultModel)
	if audio != nil {
		out += fmt.Sprintf(audioConfigYAML, audio.BaseURL, audio.STTModel, audio.BaseURL, audio.TTSModel, audio.TTSVoice)
	}
	if mnemosyneEnabled {
		out += mnemosyneConfigYAML
	}
	return out
}

// EnvFile is HermesTenantConfigTemplate.envFile: the API_SERVER_* block, the
// gateways' env-vars sorted by name, then the audio credential.
func EnvFile(apiKey string, gateways []GatewaySeed, audio *AudioProxySeed) string {
	lines := []string{
		"# Auto-generated by HermesContainerManager (HER-254).",
		"API_SERVER_KEY=" + apiKey,
		"API_SERVER_ENABLED=true",
		"API_SERVER_HOST=0.0.0.0",
		"API_SERVER_PORT=8642",
	}
	vars := map[string]string{}
	for _, gw := range gateways {
		for k, v := range GatewayEnvVars(gw.GatewayID, gw.Config) {
			vars[k] = v
		}
	}
	if len(vars) > 0 {
		keys := make([]string, 0, len(vars))
		for k := range vars {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		lines = append(lines, "", "# Messaging gateways (token presence activates the platform).")
		for _, k := range keys {
			lines = append(lines, k+"="+envQuote(vars[k]))
		}
	}
	if audio != nil {
		lines = append(lines, "", "# Speech credentials for the LuminaVault audio proxy.",
			"VOICE_TOOLS_OPENAI_KEY="+envQuote(audio.Token),
			"STT_OPENAI_BASE_URL="+envQuote(audio.BaseURL))
	}
	return strings.Join(lines, "\n")
}

// envQuote single-quotes a value for python-dotenv, stripping any embedded quote.
func envQuote(v string) string { return "'" + strings.ReplaceAll(v, "'", "") + "'" }

// Seed is HermesTenantConfigTemplate.seed: config.yaml and .env at the volume
// root, each rewritten only when its SHA-256 differs from the rendering.
func Seed(volumePath, apiKey, defaultModel string, gateways []GatewaySeed, mnemosyneEnabled bool, audio *AudioProxySeed) error {
	if err := os.MkdirAll(volumePath, 0o755); err != nil { //nolint:gosec // the volume is bind-mounted into the container, as Swift creates it
		return &SeedError{Path: volumePath, Underlying: err}
	}
	if err := writeIfDrifted(filepath.Join(volumePath, "config.yaml"), ConfigYAML(defaultModel, mnemosyneEnabled, audio)); err != nil {
		return err
	}
	return writeIfDrifted(filepath.Join(volumePath, ".env"), EnvFile(apiKey, gateways, audio))
}

func writeIfDrifted(path, content string) error {
	desired := []byte(content)
	if existing, err := os.ReadFile(path); err == nil { //nolint:gosec // path is under the operator's data root
		a, b := sha256.Sum256(existing), sha256.Sum256(desired)
		if bytes.Equal(a[:], b[:]) {
			return nil
		}
	}
	tmp := path + ".tmp." + strings.ToUpper(uuid.NewString())
	if err := os.WriteFile(tmp, desired, 0o644); err != nil { //nolint:gosec // Foundation's default mode for Data.write
		_ = os.Remove(tmp)
		return &SeedError{Path: path, Underlying: err}
	}
	_ = os.Remove(path)
	if err := os.Rename(tmp, path); err != nil {
		_ = os.Remove(tmp)
		return &SeedError{Path: path, Underlying: err}
	}
	return nil
}
