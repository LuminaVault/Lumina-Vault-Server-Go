// GatewaySeed is HermesGatewaySeed: one tenant gateway's decrypted config, keyed
// by catalog field key (bot_token, …).
type GatewaySeed struct {
	GatewayID string
	Config    map[string]string
}

// AudioProxySeed is HermesAudioProxySeed: points a tenant's Hermes speech at the
// LuminaVault audio proxy.
type AudioProxySeed struct {
	// BaseURL includes the /v1 suffix.
	BaseURL  string
	Token    string
	STTModel string
	TTSModel string
	TTSVoice string
}

// NewAudioProxySeed applies Swift's defaults (whisper-1, tts-1, lumina).
func NewAudioProxySeed(baseURL, token string) *AudioProxySeed {
	return &AudioProxySeed{BaseURL: baseURL, Token: token, STTModel: "whisper-1", TTSModel: "tts-1", TTSVoice: "lumina"}
}

// SeedError is HermesTenantConfigTemplate.SeedError.ioFailure.
type SeedError struct {
	Path       string
	Underlying error
}

func (e *SeedError) Error() string {
	return fmt.Sprintf("ioFailure(path: %q, underlying: %q)", e.Path, e.Underlying.Error())
}

func (e *SeedError) Unwrap() error { return e.Underlying }

