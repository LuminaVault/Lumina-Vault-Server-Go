#!/usr/bin/env bash
# Phase 0 Task 0.5: the goose baseline from a fresh Swift `migrate`.
#
#   scripts/schema-snapshot.sh [out-dir]      (default internal/migrations/sql)
#
# Writes into out-dir:
#   00001_baseline.sql   -- +goose Up: schema-only dump + the rows migrations seed
#   fluent-manifest.txt  every _fluent_migrations name, for `migrate --adopt-fluent`
#   schema-swift.sql     normalized schema-only dump; the schema-parity check
#                        diffs a goose-migrated DB against it
# Uses the parity compose Postgres (pg18, same as CI) and pg_dump inside it,
# so client and server versions always match.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT="${1:-internal/migrations/sql}"
: "${PARITY_SWIFT_IMAGE:=lv-swift:fdbed9b0}"
export PARITY_SWIFT_IMAGE
COMPOSE=(docker compose -f docker-compose.parity.yml -p lvparity)
DB=schema_snapshot

"${COMPOSE[@]}" up -d --wait pg
pg() { "${COMPOSE[@]}" exec -T pg "$@"; }
pg psql -v ON_ERROR_STOP=1 -q -U lv -d postgres -c "DROP DATABASE IF EXISTS $DB WITH (FORCE)" -c "CREATE DATABASE $DB"
"${COMPOSE[@]}" run --rm --no-deps -e POSTGRES_DATABASE=$DB swift migrate

dump_opts=(--no-owner --no-privileges --no-comments -U lv -d "$DB")
schema="$(pg pg_dump --schema-only "${dump_opts[@]}" --exclude-table=_fluent_migrations)"

# Tables that hold rows right after a fresh migrate (seed data written by
# migrations), excluding Fluent's own bookkeeping.
seeded="$(pg psql -At -U lv -d "$DB" -c "
  SELECT string_agg(format('--table=%I.%I', schemaname, relname), ' ')
  FROM pg_stat_user_tables
  WHERE relname <> '_fluent_migrations' AND n_live_tup > 0")"
# pg_stat counters lag; fall back to an exact count per table.
if [ -z "$seeded" ]; then
  seeded="$(pg psql -At -U lv -d "$DB" -c "
    DO \$\$ DECLARE r record; n bigint; acc text := ''; BEGIN
      FOR r IN SELECT schemaname, tablename FROM pg_tables WHERE schemaname='public' AND tablename <> '_fluent_migrations' LOOP
        EXECUTE format('SELECT count(*) FROM %I.%I', r.schemaname, r.tablename) INTO n;
        IF n > 0 THEN acc := acc || format(' --table=%I.%I', r.schemaname, r.tablename); END IF;
      END LOOP;
      RAISE NOTICE '%', acc;
    END \$\$;" 2>&1 | sed -n 's/^NOTICE:  //p')"
fi
data=""
if [ -n "${seeded// /}" ]; then
  # shellcheck disable=SC2086
  data="$(pg pg_dump --data-only --inserts "${dump_opts[@]}" $seeded)"
fi

mkdir -p "$OUT"
{
  echo "-- Generated by scripts/schema-snapshot.sh from $PARITY_SWIFT_IMAGE. Do not edit."
  echo "-- +goose Up"
  echo "-- +goose StatementBegin"
  printf '%s\n' "$schema" | grep -vE '^SELECT pg_catalog.set_config|^SET |^\\(un)?restrict '
  printf '%s\n' "$data" | grep -vE '^SELECT pg_catalog.set_config|^SET |^\\(un)?restrict '
  echo "-- +goose StatementEnd"
  echo "-- +goose Down"
  echo "SELECT 'the baseline cannot be rolled back' AS refusing, 1/0;"
} > "$OUT/00001_baseline.sql"

pg psql -At -U lv -d "$DB" -c "SELECT name FROM _fluent_migrations ORDER BY batch, name" > "$OUT/fluent-manifest.txt"

printf '%s\n' "$schema" | grep -vE '^--|^$|^SELECT pg_catalog.set_config|^SET |^\\(un)?restrict ' > "$OUT/schema-swift.sql"

echo "baseline: $(wc -l < "$OUT/00001_baseline.sql") lines; fluent migrations: $(wc -l < "$OUT/fluent-manifest.txt"); seeded tables: ${seeded:-none}"
